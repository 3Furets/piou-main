const fs   = require("fs");
const path = require("path");
const TARGET = path.join(__dirname, "ximi-assistant", "ximi_assistant.py");

const PY = [];
PY.push(`#!/usr/bin/env python3`);
PY.push(`"""ximi_assistant.py - Assistant Ximi Local"""`);
PY.push(``);
PY.push(`import os, re, sys, json, subprocess, logging`);
PY.push(`from datetime import datetime, date, timedelta`);
PY.push(`from pathlib import Path`);
PY.push(``);
PY.push(`import pandas as pd`);
PY.push(`try:`);
PY.push(`    import duckdb`);
PY.push(`except ImportError:`);
PY.push(`    duckdb = None`);
PY.push(`try:`);
PY.push(`    import ollama`);
PY.push(`except ImportError:`);
PY.push(`    ollama = None`);
PY.push(``);
PY.push(`BASE_DIR   = Path(__file__).parent`);
PY.push(`SCRAPER_JS = BASE_DIR / "extracteurs" / "ximi_scraper.js"`);
PY.push(`RAPPORTS   = BASE_DIR / "rapports"`);
PY.push(`RAPPORTS.mkdir(exist_ok=True)`);
PY.push(`MODEL = "llama3.1:8b"`);
PY.push(``);
PY.push(`logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s", datefmt="%H:%M:%S")`);
PY.push(`log = logging.getLogger("ximi")`);
PY.push(``);
PY.push(`MOIS_FR = {`);
PY.push(`    "janvier":1,"fevrier":2,"mars":3,"avril":4,"mai":5,"juin":6,`);
PY.push(`    "juillet":7,"aout":8,"septembre":9,"octobre":10,"novembre":11,"decembre":12`);
PY.push(`}`);
PY.push(``);
PY.push(`def normaliser(s):`);
PY.push(`    import unicodedata`);
PY.push(`    return unicodedata.normalize('NFD', s).encode('ascii','ignore').decode().lower().strip()`);
PY.push(``);
PY.push(`def extraire_date(question):`);
PY.push(`    q = question.lower()`);
PY.push(`    m = re.search(r'\\b(\\d{1,2})[/\\-](\\d{1,2})[/\\-](\\d{4})\\b', question)`);
PY.push(`    if m:`);
PY.push(`        j,mo,a = m.groups()`);
PY.push(`        return f"{a}-{int(mo):02d}-{int(j):02d}"`);
PY.push(`    motif = "|".join(MOIS_FR.keys())`);
PY.push(`    m2 = re.search(rf'\\b(\\d{{1,2}})(?:er)?\\s+({motif})(?:\\s+(\\d{{4}}))?\\b', normaliser(q))`);
PY.push(`    if m2:`);
PY.push(`        j=int(m2.group(1)); mo=MOIS_FR[m2.group(2)]; a=int(m2.group(3)) if m2.group(3) else datetime.now().year`);
PY.push(`        return f"{a}-{mo:02d}-{j:02d}"`);
PY.push(`    aujourd = date.today()`);
PY.push(`    if any(x in q for x in ["aujourd","ce soir","ce matin"]): return str(aujourd)`);
PY.push(`    if "demain" in q: return str(aujourd + timedelta(days=1))`);
PY.push(`    if "hier" in q:   return str(aujourd - timedelta(days=1))`);
PY.push(`    return None`);
PY.push(``);
PY.push(`def extraire_mois(question):`);
PY.push(`    q = normaliser(question)`);
PY.push(`    motif = "|".join(MOIS_FR.keys())`);
PY.push(`    m = re.search(rf'\\b({motif})(?:\\s+(\\d{{4}}))?\\b', q)`);
PY.push(`    if m:`);
PY.push(`        mo=MOIS_FR[m.group(1)]; a=int(m.group(2)) if m.group(2) else datetime.now().year`);
PY.push(`        return f"{a}-{mo:02d}"`);
PY.push(`    if "ce mois" in q or "mois en cours" in q: return datetime.now().strftime("%Y-%m")`);
PY.push(`    return None`);
PY.push(``);
PY.push(`def extraire_nom_personne(question):`);
PY.push(`    """Detecte un nom propre dans la question (NOM Prenom ou Prenom NOM)"""`);
PY.push(`    q = question.strip()`);
PY.push(`    # Patterns : "de X", "pour X", "horaires de X", nom en majuscules`);
PY.push(`    patterns = [`);
PY.push(`        r"(?:de|pour|intervenant|agent)\\s+([A-Z][a-zA-Z\\-]+(?:\\s+[A-Z][a-zA-Z\\-]+)+)",`);
PY.push(`        r"([A-Z]{2,}(?:\\s+[A-Z][a-zA-Z\\-]+)+)",`);
PY.push(`        r"([A-Z][a-zA-Z\\-]+\\s+[A-Z]{2,})",`);
PY.push(`    ]`);
PY.push(`    for pat in patterns:`);
PY.push(`        m = re.search(pat, q)`);
PY.push(`        if m: return m.group(1).strip()`);
PY.push(`    return None`);
PY.push(``);
PY.push(`def detecter_intention(question):`);
PY.push(`    q = normaliser(question)`);
PY.push(`    date_str = extraire_date(question)`);
PY.push(`    mois_str = extraire_mois(question)`);
PY.push(`    nom_str  = extraire_nom_personne(question)`);
PY.push(`    mots_mois = ["mois","semaine","periode","mensuel"]`);
PY.push(`    if date_str:`);
PY.push(`        type_req = "planning_jour"`);
PY.push(`    elif mois_str or any(m in q for m in mots_mois):`);
PY.push(`        type_req = "planning_mois"`);
PY.push(`        if not mois_str: mois_str = datetime.now().strftime("%Y-%m")`);
PY.push(`    else:`);
PY.push(`        type_req = "planning_jour"`);
PY.push(`        date_str = str(date.today())`);
PY.push(`    return { "type": type_req, "date": date_str, "mois": mois_str, "nom": nom_str }`);
PY.push(``);
PY.push(`def lancer_scraper(intention):`);
PY.push(`    fichier_sortie = RAPPORTS / f"extraction_{datetime.now().strftime('%H%M%S')}.json"`);
PY.push(`    if intention["type"] == "planning_jour":`);
PY.push(`        commande, param = "planning_jour", intention["date"] or str(date.today())`);
PY.push(`    else:`);
PY.push(`        commande, param = "planning_mois", intention["mois"] or datetime.now().strftime("%Y-%m")`);
PY.push(`    log.info(f"Lancement scraper : node {SCRAPER_JS.name} {commande} {param}")`);
PY.push(`    try:`);
PY.push(`        proc = subprocess.run(`);
PY.push(`            ["node", str(SCRAPER_JS), commande, param, str(fichier_sortie)],`);
PY.push(`            capture_output=True, text=True, timeout=180, cwd=str(BASE_DIR)`);
PY.push(`        )`);
PY.push(`        if proc.stderr:`);
PY.push(`            for l in proc.stderr.strip().split("\\n"):`);
PY.push(`                if l.strip(): log.info(f"[scraper] {l}")`);
PY.push(`        if proc.returncode != 0: return {"erreur": proc.stderr or "Erreur inconnue"}`);
PY.push(`        if proc.stdout.strip():`);
PY.push(`            try: return json.loads(proc.stdout)`);
PY.push(`            except: pass`);
PY.push(`        if fichier_sortie.exists(): return json.loads(fichier_sortie.read_text())`);
PY.push(`        return {"erreur": "Aucune donnee retournee"}`);
PY.push(`    except subprocess.TimeoutExpired: return {"erreur": "Timeout 180s"}`);
PY.push(`    except FileNotFoundError:         return {"erreur": "Node.js introuvable"}`);
PY.push(`    except Exception as e:            return {"erreur": str(e)}`);
PY.push(``);
PY.push(`def analyser(donnees, question, intention):`);
PY.push(`    if "erreur" in donnees: return f"Erreur : {donnees['erreur']}"`);
PY.push(`    evenements = donnees.get("evenements", [])`);
PY.push(`    if not evenements:`);
PY.push(`        return f"Aucun evenement trouve pour {donnees.get('date') or donnees.get('mois') or '?'}."`);
PY.push(`    df       = pd.DataFrame(evenements)`);
PY.push(`    log.info(f"DataFrame : {len(df)} lignes, colonnes : {list(df.columns)}")`);
PY.push(`    q        = normaliser(question)`);
PY.push(`    type_req = intention.get("type")`);
PY.push(`    stats    = donnees.get("stats_types", {})`);
PY.push(`    nom_cible = intention.get("nom")`);
PY.push(``);
PY.push(`    def stats_str():`);
PY.push(`        return "  (" + ", ".join(f"{k}: {v}" for k,v in stats.items()) + ")" if stats else ""`);
PY.push(``);
PY.push(`    col = "nom_intervenant"`);
PY.push(`    if col not in df.columns:`);
PY.push(`        col = next((c for c in df.columns if "nom" in c.lower()), None)`);
PY.push(``);
PY.push(`    # --- Recherche par nom specifique ---`);
PY.push(`    if nom_cible and col:`);
PY.push(`        nom_norm = normaliser(nom_cible)`);
PY.push(`        mask = df[col].apply(lambda x: nom_norm in normaliser(str(x)) if pd.notna(x) else False)`);
PY.push(`        df_nom = df[mask].copy()`);
PY.push(`        if df_nom.empty:`);
PY.push(`            return f"Aucun evenement trouve pour '{nom_cible}'."`);
PY.push(`        periode = donnees.get("date") or donnees.get("mois") or "?"`);
PY.push(`        out = [f"", f"Planning de {nom_cible} -- {periode} -- {len(df_nom)} evenement(s)", ""]`);
PY.push(`        df_nom = df_nom.sort_values("debut")`);
PY.push(`        for _, row in df_nom.iterrows():`);
PY.push(`            d = str(row.get("debut_formate") or "").strip()`);
PY.push(`            f = str(row.get("fin_formate")   or "").strip()`);
PY.push(`            client = str(row.get("client") or "").strip()`);
PY.push(`            prest  = str(row.get("prestation") or "").strip()`);
PY.push(`            statut = str(row.get("statut") or "").strip()`);
PY.push(`            debut_date = str(row.get("debut") or "")[:10]`);
PY.push(`            hor = f"{d}-{f}" if d and f and d != "nan" and f != "nan" else d`);
PY.push(`            detail = " | ".join(filter(None, [client, prest, statut]))`);
PY.push(`            out.append(f"  {debut_date}  {hor:<12}  {detail}")`);
PY.push(`        return "\\n".join(out)`);
PY.push(``);
PY.push(`    if type_req == "planning_jour":`);
PY.push(`        date_str = donnees.get("date","?")`);
PY.push(`        demande_absences = any(x in q for x in ["absent","absence","conge","ne travaille pas","travaille pas"])`);
PY.push(`        demande_interv   = any(x in q for x in ["intervention","client","prestation"])`);
PY.push(`        if demande_absences:`);
PY.push(`            df_f = df[df["type_event"]=="AgentAbsence"].copy(); titre=f"Absences du {date_str}"`);
PY.push(`        elif demande_interv:`);
PY.push(`            df_f = df[df["type_event"]=="Intervention"].copy(); titre=f"Interventions du {date_str}"`);
PY.push(`        else:`);
PY.push(`            df_f = df[df["type_event"].isin(["Intervention","AgentAbsence","AgentEvent"])].copy()`);
PY.push(`            titre = f"Planning du {date_str}"`);
PY.push(`        out = ["", f"{titre} -- {len(df)} evenement(s) total", stats_str(), ""]`);
PY.push(`        if col and df_f[col].notna().any():`);
PY.push(`            interv = sorted(df_f[df_f[col].str.strip()!=""][col].dropna().unique().tolist(), key=lambda x:x.strip().upper())`);
PY.push(`            out.append(f"{len(interv)} intervenant(s) :")`);
PY.push(`            out.append("")`);
PY.push(`            for nom in interv:`);
PY.push(`                sous = df_f[df_f[col]==nom]`);
PY.push(`                nb_ev = len(sous)`);
PY.push(`                horaires = []`);
PY.push(`                for _, row in sous.iterrows():`);
PY.push(`                    d = str(row.get("debut_formate") or "").strip()`);
PY.push(`                    f = str(row.get("fin_formate")   or "").strip()`);
PY.push(`                    if d and d!="nan": horaires.append(f"{d}-{f}" if f and f!="nan" else d)`);
PY.push(`                hor = "  |  ".join(horaires[:3])`);
PY.push(`                if len(horaires)>3: hor += f" (+{len(horaires)-3})"`);
PY.push(`                out.append(f"  {nom:<35} {nb_ev:>3} ev.   {hor}")`);
PY.push(`        else: out.append("(aucun nom disponible)")`);
PY.push(`        return "\\n".join(out)`);
PY.push(``);
PY.push(`    elif type_req == "planning_mois":`);
PY.push(`        mois_str = donnees.get("mois","?")`);
PY.push(`        df_i = df[df["type_event"]=="Intervention"] if "type_event" in df.columns else df`);
PY.push(`        out  = ["", f"Planning du mois {mois_str} -- {len(df)} evenement(s)", stats_str(), ""]`);
PY.push(`        if col and col in df_i.columns:`);
PY.push(`            cpt = df_i[df_i[col].str.strip()!=""].groupby(col).size().reset_index(name="nb")`);
PY.push(`            cpt = cpt.sort_values(col, key=lambda s: s.str.upper())`);
PY.push(`            out.append(f"{len(cpt)} intervenant(s) avec interventions :")`);
PY.push(`            out.append("")`);
PY.push(`            for _, row in cpt.iterrows():`);
PY.push(`                out.append(f"  {row[col]:<35} {row['nb']:>4} intervention(s)")`);
PY.push(`        return "\\n".join(out)`);
PY.push(`    return f"Donnees extraites : {len(df)} lignes"`);
PY.push(``);
PY.push(`def sauvegarder_rapport(question, donnees, reponse):`);
PY.push(`    ts = datetime.now().strftime("%Y%m%d_%H%M%S")`);
PY.push(`    f  = RAPPORTS / f"rapport_{ts}.md"`);
PY.push(`    f.write_text(f"# Rapport Ximi\\n\\n## Question\\n{question}\\n\\n## Reponse\\n{reponse}\\n", encoding="utf-8")`);
PY.push(`    log.info(f"Rapport sauvegarde : {f.name}")`);
PY.push(``);
PY.push(`def main():`);
PY.push(`    print("\\n" + "="*55)`);
PY.push(`    print("ASSISTANT XIMI - Planning en direct")`);
PY.push(`    print("="*55)`);
PY.push(`    print("Exemples :")`);
PY.push(`    print("  -> Qui travaille demain ?")`);
PY.push(`    print("  -> Horaires de DARDENNE Valentin tout septembre")`);
PY.push(`    print("  -> Planning du mois de septembre 2026")`);
PY.push(`    print("  -> Qui est absent aujourd'hui ?")`);
PY.push(`    print("  -> 'quit' pour quitter")`);
PY.push(`    print("="*55 + "\\n")`);
PY.push(`    while True:`);
PY.push(`        try: question = input("Question : ").strip()`);
PY.push(`        except KeyboardInterrupt: print("\\nAu revoir !"); break`);
PY.push(`        if question.lower() in ("quit","exit","q"): print("Au revoir !"); break`);
PY.push(`        if not question: continue`);
PY.push(`        intention = detecter_intention(question)`);
PY.push(`        print(f"\\nType : {intention['type']}", end="")`);
PY.push(`        if intention.get("date"): print(f" | Date : {intention['date']}", end="")`);
PY.push(`        if intention.get("mois"): print(f" | Mois : {intention['mois']}", end="")`);
PY.push(`        if intention.get("nom"):  print(f" | Nom  : {intention['nom']}", end="")`);
PY.push(`        print()`);
PY.push(`        print("Extraction depuis Ximi en cours...")`);
PY.push(`        donnees = lancer_scraper(intention)`);
PY.push(`        if "erreur" in donnees: print(f"\\nErreur : {donnees['erreur']}\\n"); continue`);
PY.push(`        nb = donnees.get("nb_evenements","?")`);
PY.push(`        print(f"{nb} element(s) extrait(s)")`);
PY.push(`        reponse = analyser(donnees, question, intention)`);
PY.push(`        print("\\n" + "="*55)`);
PY.push(`        print("REPONSE :")`);
PY.push(`        print(reponse)`);
PY.push(`        print("="*55 + "\\n")`);
PY.push(`        sauvegarder_rapport(question, donnees, reponse)`);
PY.push(``);
PY.push(`if __name__ == "__main__":`);
PY.push(`    main()`);

